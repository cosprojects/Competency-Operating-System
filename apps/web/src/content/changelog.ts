/**
 * Лог обновлений системы (блок «Лог обновлений» на главной).
 *
 * Контракт для агента, который публикует записи каждый день:
 *
 *  1. `date`        — текущая дата публикации, строка `YYYY-MM-DD` (ISO, без времени).
 *  2. `title`       — общее название проведённых работ: «Работа над дизайном»,
 *                     «Общие улучшения», «Переработка структуры раздела такой-то».
 *                     До ~60 символов, без точки в конце.
 *  3. `description` — описание работ ровно тремя предложениями (до ~450 символов):
 *                     что сделано, что это меняет для пользователя и что дальше.
 *
 * Правила: новые записи добавляются в начало файла, даты — по убыванию, одна
 * запись в день. На главной показываются три последние записи.
 */
